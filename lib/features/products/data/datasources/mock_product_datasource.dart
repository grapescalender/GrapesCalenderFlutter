/// Mock API data source — simulates GET /api/v1/products
/// Contains 20+ products per category (Pesticides, Insecticides, Fungicides,
/// Fertilizers, Nutrition, Growth Regulators, Bio Products).
abstract class ProductApiService {
  Future<List<ProductModel>> getProducts({String? category});
  Future<ProductModel> getProductById(String id);
  Future<List<ProductModel>> searchProducts({
    String? keyword,
    String? category,
    String? stage,
    String? company,
  });
  Future<List<ProductModel>> getRecommendedProducts({required String stage});
}

class MockProductDataSource implements ProductApiService {
  // Simulate network latency
  static const _delay = Duration(milliseconds: 350);

  @override
  Future<List<ProductModel>> getProducts({String? category}) async {
    await Future.delayed(_delay);
    if (category == null || category == 'all') return _all;
    return _all.where((p) => p.category == category).toList();
  }

  @override
  Future<ProductModel> getProductById(String id) async {
    await Future.delayed(_delay);
    return _all.firstWhere(
      (p) => p.id == id,
      orElse: () => throw Exception('Product not found: $id'),
    );
  }

  @override
  Future<List<ProductModel>> searchProducts({
    String? keyword,
    String? category,
    String? stage,
    String? company,
  }) async {
    await Future.delayed(_delay);
    var results = List<ProductModel>.from(_all);
    if (category != null && category != 'all') {
      results = results.where((p) => p.category == category).toList();
    }
    if (stage != null && stage.isNotEmpty) {
      results = results
          .where((p) => p.recommendedStages
              .any((s) => s.toLowerCase().contains(stage.toLowerCase())))
          .toList();
    }
    if (company != null && company.isNotEmpty) {
      results = results
          .where((p) =>
              p.company.toLowerCase().contains(company.toLowerCase()))
          .toList();
    }
    if (keyword != null && keyword.isNotEmpty) {
      final kw = keyword.toLowerCase();
      results = results
          .where((p) =>
              p.name.toLowerCase().contains(kw) ||
              p.description.toLowerCase().contains(kw) ||
              p.company.toLowerCase().contains(kw))
          .toList();
    }
    return results;
  }

  @override
  Future<List<ProductModel>> getRecommendedProducts(
      {required String stage}) async {
